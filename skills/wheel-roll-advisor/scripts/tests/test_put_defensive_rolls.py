def _nok_put_position():
    """NOK-shaped: 10× short $11P, spot $9.27 — the 2026-07-30 briefing
    proposed rolling into 10× $1P at bid $0.00 / mid $0.00 ('0.0% yield on
    new collateral', '10 spreads @ $0.00/share')."""
    return {
        "symbol": "NOK", "positionType": "SHORT_PUT", "optionType": "PUT",
        "strikePrice": 11.0, "expirationDate": "2026-09-18", "quantity": 10,
        "entryPrice": 1.45, "currentMid": 2.08, "daysToExpiry": 50,
        "ivRank": 55, "underlyingPrice": 9.27,
    }


def _nok_leg(exp, strike, bid, ask, dte, delta):
    return {"expirationDate": exp, "strikePrice": strike, "optionType": "PUT",
            "bid": bid, "ask": ask, "daysToExpiry": dte, "delta": delta,
            "openInterest": 500}


def test_sto_leg_viability_floor():
    """NOK-shaped: the only strike below the roll-down target is a $1P at
    bid $0.00 — a garbage ticket (rule #19). No roll-down candidate may be
    generated; the $1P must never appear."""
    chain = {"candidates": [
        _nok_leg("2026-09-18", 11.0, 2.00, 2.15, 50, -0.72),
        # next expiration: same strike viable, but only a dead $1P below
        _nok_leg("2026-10-16", 11.0, 2.30, 2.50, 78, -0.70),
        _nok_leg("2026-10-16", 1.0, 0.00, 0.05, 78, -0.01),
        # filler expirations so current_exp_idx + 3 exists
        _nok_leg("2026-11-20", 11.0, 2.60, 2.80, 113, -0.68),
        _nok_leg("2026-12-18", 11.0, 2.85, 3.05, 141, -0.66),
    ]}
    cands = enumerate_roll_candidates(_nok_put_position(), chain, _params())
    strikes = [c.instruction["sell_strike"] for c in _non_hold(cands)]
    assert 1.0 not in strikes, f"dead $1P STO leg offered: {strikes}"
    assert all(s == 11.0 for s in strikes), (
        f"only the viable same-strike rolls should remain: {strikes}")


def test_sto_leg_viability_floor_rejects_subdime_mid():
    """A bid > 0 but mid < $0.10 STO leg is still not viable."""
    chain = {"candidates": [
        _nok_leg("2026-09-18", 11.0, 2.00, 2.15, 50, -0.72),
        _nok_leg("2026-10-16", 11.0, 2.30, 2.50, 78, -0.70),
        _nok_leg("2026-10-16", 6.0, 0.05, 0.08, 78, -0.06),  # mid $0.065
        _nok_leg("2026-11-20", 11.0, 2.60, 2.80, 113, -0.68),
        _nok_leg("2026-12-18", 11.0, 2.85, 3.05, 141, -0.66),
    ]}
    cands = enumerate_roll_candidates(_nok_put_position(), chain, _params())
    strikes = [c.instruction["sell_strike"] for c in _non_hold(cands)]
    assert 6.0 not in strikes


def test_sto_leg_viability_floor_keeps_viable_roll_down():
    """A genuinely viable roll-down (bid > 0, mid ≥ $0.10, |δ| ≥ 0.05,
    strike ≥ 40% of spot) still comes through — the floor is a floor, not a
    roll-down ban."""
    chain = {"candidates": [
        _nok_leg("2026-09-18", 11.0, 2.00, 2.15, 50, -0.72),
        _nok_leg("2026-10-16", 11.0, 2.30, 2.50, 78, -0.70),
        _nok_leg("2026-10-16", 6.0, 0.35, 0.45, 78, -0.14),
        _nok_leg("2026-11-20", 11.0, 2.60, 2.80, 113, -0.68),
        _nok_leg("2026-12-18", 11.0, 2.85, 3.05, 141, -0.66),
    ]}
    cands = enumerate_roll_candidates(_nok_put_position(), chain, _params())
    strikes = [c.instruction["sell_strike"] for c in _non_hold(cands)]
    assert 6.0 in strikes, f"viable roll-down was wrongly filtered: {strikes}"


def test_ranker_belt_rejects_dead_quote_and_sub40pct_strike():
    """candidate_ranker's put-mode belt: candidates that CARRY quote keys
    showing a dead leg (no bid, mid < $0.10), or a strike below 40% of spot,
    are never picked. Candidates WITHOUT quote keys are unaffected
    (fail-open for legacy callers / fixtures)."""
    cands = [
        {"id": "A", "netDollars": 0, "dteExtension": 0, "instruction": None,
         "current_strike": 11.0},
        # dead-quote roll-down — massive "reduction" but bid 0 / mid 0
        {"id": "B", "netDollars": -2085.0, "dteExtension": 28,
         "instruction": {"sell_strike": 5.0, "sell_expiration": "2026-10-16",
                         "sell_bid": 0.0, "sell_mid": 0.0, "sell_ask": 0.05},
         "current_strike": 11.0},
        # sub-40%-of-spot strike (no quote keys — strike floor still applies)
        {"id": "C", "netDollars": -2000.0, "dteExtension": 28,
         "instruction": {"sell_strike": 1.0, "sell_expiration": "2026-10-16"},
         "current_strike": 11.0},
        # legit same-strike out, small credit, no quote keys (fail-open)
        {"id": "D", "netDollars": 220.0, "dteExtension": 28,
         "instruction": {"sell_strike": 11.0, "sell_expiration": "2026-10-16"},
         "current_strike": 11.0},
    ]
    best, _ = rank_candidates(cands, spot=9.27, option_type="PUT",
                              max_tenor_days=120)
    assert best is not None
    assert best["id"] == "D", f"belt failed — picked {best['id']}"
